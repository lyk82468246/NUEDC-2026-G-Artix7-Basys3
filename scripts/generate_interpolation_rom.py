"""16-tap / 64-phase Blackman-windowed sinc, signed Q2.14; no dependencies."""
import argparse
import math
from pathlib import Path


def coefficients():
    result = []
    for phase in range(64):
        fraction = phase / 64
        row = []
        for tap in range(16):
            distance = tap - 7 - fraction
            sinc = 1.0 if distance == 0 else math.sin(math.pi * distance) / (math.pi * distance)
            window = 0.42 + 0.5 * math.cos(math.pi * distance / 8) + 0.08 * math.cos(2 * math.pi * distance / 8)
            row.append(sinc * window)
        total = sum(row)
        fixed = [round(value / total * 16384) for value in row]
        fixed[max(range(16), key=lambda i: abs(row[i]))] += 16384 - sum(fixed)
        assert sum(fixed) == 16384 and all(-32768 <= value <= 32767 for value in fixed)
        result.extend(fixed)
    return result


def verilog():
    values = coefficients()
    entries = '\n'.join(f"        rom[{i}]=16'h{value & 65535:04x};" for i, value in enumerate(values))
    return '''`timescale 1ns/1ps
// Generated by scripts/generate_interpolation_rom.py. Q2.14, unity DC sum.
// 64 fractional phases x 16 taps = one 1024x16 synchronous ROM (RAMB18).
module Display_Interpolation_ROM(input wire clk,input wire [9:0] address,
    output reg signed [15:0] coefficient);
    (* rom_style="block" *) reg signed [15:0] rom[0:1023];
    always @(posedge clk)coefficient<=rom[address];
    initial begin
''' + entries + '\n    end\nendmodule\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text = verilog()
    if args.check:
        if args.output.read_text(encoding='utf-8') != text:
            raise SystemExit('Interpolation ROM differs from generator')
    else:
        args.output.write_text(text, encoding='utf-8')


if __name__ == '__main__':
    main()
